function p = draw_device_box(ax, x_center, y_center, width, height, bg_color, border_color, title_str, subtitle_str)
% DRAW_DEVICE_BOX Draws a sleek, rounded/beveled device housing with labels.
% Compatible with MATLAB desktop and MATLAB Online.

    if nargin < 6 || isempty(bg_color), bg_color = [0.12 0.16 0.24]; end
    if nargin < 7 || isempty(border_color), border_color = [0.30 0.55 0.85]; end
    if nargin < 8, title_str = ''; end
    if nargin < 9, subtitle_str = ''; end

    hold(ax, 'on');

    half_w = width / 2;
    half_h = height / 2;

    x = [x_center - half_w, x_center + half_w, x_center + half_w, x_center - half_w];
    y = [y_center - half_h, y_center - half_h, y_center + half_h, y_center + half_h];

    % Device main chassis patch
    p = patch(ax, x, y, bg_color, ...
        'EdgeColor', border_color, ...
        'LineWidth', 2.0, ...
        'FaceAlpha', 0.88, ...
        'Tag', 'device_box');

    % Subtle top highlight line for 3D metallic feel
    plot(ax, [x_center - half_w + 0.05*width, x_center + half_w - 0.05*width], ...
             [y_center + half_h - 0.04*height, y_center + half_h - 0.04*height], ...
             'Color', [border_color 0.6], 'LineWidth', 1.2);

    % Title text above or inside
    if ~isempty(title_str)
        text(ax, x_center, y_center + half_h + 0.18*height, title_str, ...
            'Color', [0.92 0.95 0.98], ...
            'FontSize', 10.5, ...
            'FontWeight', 'bold', ...
            'HorizontalAlignment', 'center', ...
            'VerticalAlignment', 'bottom');
    end

    if ~isempty(subtitle_str)
        text(ax, x_center, y_center - half_h - 0.12*height, subtitle_str, ...
            'Color', [0.65 0.75 0.88], ...
            'FontSize', 8.5, ...
            'FontAngle', 'italic', ...
            'HorizontalAlignment', 'center', ...
            'VerticalAlignment', 'top');
    end
end
