            'FontWeight', 'bold', 'ForegroundColor', c_cyan);

        uicontrol('Parent', c1, 'Style', 'text', ...
            'Units', 'normalized', 'Position', [0.05 0.84 0.90 0.13], ...
            'String', 'Optical Isolator', ...
            'FontName', 'Segoe UI', 'FontSize', 13, 'FontWeight', 'bold', ...
