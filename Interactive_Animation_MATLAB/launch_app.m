    % ---------------------------------------------------------------------
    % NAVIGATION LOGIC
    % ---------------------------------------------------------------------
    function open_module(mod_name)
        set(p_dashboard, 'Visible', 'off');

        if strcmp(mod_name, 'isolator')
            if ~isolator_init
                animate_isolator(fig, p_isolator, @show_dashboard);
                isolator_init = true;
            end
            set(p_isolator, 'Visible', 'on');

        elseif strcmp(mod_name, 'circulator')
            if ~circulator_init
                animate_circulator(fig, p_circulator, @show_dashboard);
                circulator_init = true;
            end
            set(p_circulator, 'Visible', 'on');

        elseif strcmp(mod_name, 'wdm')
            if ~wdm_init
                animate_wdm(fig, p_wdm, @show_dashboard);
                wdm_init = true;
            end
            set(p_wdm, 'Visible', 'on');
        end
    end

    function show_dashboard()
        set(p_isolator, 'Visible', 'off');
        set(p_circulator, 'Visible', 'off');
        set(p_wdm, 'Visible', 'off');
        set(p_dashboard, 'Visible', 'on');
    end
end
