            'String', sprintf('Demonstrates non-reciprocal light transmission using Faraday rotation.\n\n* Forward: Low insertion loss (0.5 dB)\n* Reverse: High isolation (>= 30 dB)\n* Protects laser from optical feedback\n* Jones matrix polarization model'), ...
