            'ForegroundColor', c_subtext, 'BackgroundColor', c_card, ...
            'HorizontalAlignment', 'left');

        uicontrol('Parent', c1, 'Style', 'pushbutton', ...
            'Units', 'normalized', 'Position', [0.08 0.06 0.84 0.17], ...
            'String', 'Launch Isolator Simulation', ...
            'FontName', 'Segoe UI', 'FontSize', 10, 'FontWeight', 'bold', ...
            'ForegroundColor', [0.05 0.08 0.15], 'BackgroundColor', c_cyan, ...
            'Callback', @(~, ~) open_module('isolator'));

