        c2 = uipanel('Parent', p_dashboard, 'Units', 'normalized', ...
            'Position', [start_x + (card_w + gap), 0.29, card_w, card_h], ...
            'BackgroundColor', c_card, 'BorderColor', c_border, ...
            'HighlightColor', [0.3 0.8 0.5], ...
            'Title', ' MODULE B ', 'FontName', 'Segoe UI', 'FontSize', 10, ...
            'FontWeight', 'bold', 'ForegroundColor', c_green);

        uicontrol('Parent', c2, 'Style', 'text', ...
            'Units', 'normalized', 'Position', [0.05 0.84 0.90 0.13], ...
            'String', 'Optical Circulator', ...
            'FontName', 'Segoe UI', 'FontSize', 13, 'FontWeight', 'bold', ...
            'ForegroundColor', [1 1 1], 'BackgroundColor', c_card, ...
            'HorizontalAlignment', 'center');

        uicontrol('Parent', c2, 'Style', 'text', ...
            'Units', 'normalized', 'Position', [0.06 0.26 0.88 0.56], ...
            'String', sprintf('Demonstrates fundamental 3-port cyclic optical routing.\n\n* Route: Port 1 -> 2 -> 3 -> 1\n* Selectable input ports (1, 2, or 3)\n* Continuous geometric pulse paths\n* Ideal and Realistic transfer matrix\n* Real-time routing status updates'), ...
            'FontName', 'Segoe UI', 'FontSize', 8.5, ...
