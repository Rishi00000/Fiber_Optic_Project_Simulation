function launch_app()
% LAUNCH_APP Master Interactive Dashboard for Fiber Optic Device Simulations.
% Title: "Simulation of Fiber Optic Isolator, Circulator, and Wavelength Division Multiplexing (WDM)"
%
% This application is 100% software-based, built with base MATLAB graphics
% to ensure flawless execution in MATLAB Online and desktop MATLAB.
%
% Usage:
%   launch_app
% Or in MATLAB Online:
%   Open launch_app.m and click "Run".

    % Ensure helpers and current directory are on MATLAB path
    app_dir = fileparts(mfilename('fullpath'));
    addpath(app_dir);
    addpath(fullfile(app_dir, 'helpers'));

    % Close existing instance if open
    close(findobj('Type', 'figure', 'Name', 'Fiber Optic Interactive Simulation Suite'));

    % Palette: Dark navy/charcoal scientific theme
    c_bg      = [0.06 0.08 0.13];
    c_panel   = [0.09 0.12 0.19];
    c_card    = [0.12 0.16 0.25];
    c_card_h  = [0.16 0.22 0.34];
    c_border  = [0.22 0.32 0.48];
    c_cyan    = [0.00 0.90 1.00];
    c_blue    = [0.20 0.60 1.00];
    c_green   = [0.00 0.90 0.45];
    c_amber   = [1.00 0.78 0.15];
    c_text    = [0.94 0.96 0.99];
    c_subtext = [0.65 0.75 0.88];

    % Master Figure: Auto-scaled to fit laptop screens and MATLAB Online
    scr = get(0, 'ScreenSize');
    fig_w = min(1140, max(750, round(scr(3) * 0.92)));
    fig_h = min(580, max(460, round(scr(4) * 0.74)));
    fig_x = max(15, round((scr(3) - fig_w) / 2));
    fig_y = max(45, round((scr(4) - fig_h) / 2));

    fig = figure('Name', 'Fiber Optic Interactive Simulation Suite', ...
        'NumberTitle', 'off', ...
        'Color', c_bg, ...
        'Position', [fig_x fig_y fig_w fig_h], ...
        'MenuBar', 'none', ...
        'ToolBar', 'none', ...
        'Resize', 'on');

    % Main Container Panels
    p_dashboard = uipanel('Parent', fig, 'Units', 'normalized', ...
        'Position', [0 0 1 1], 'BackgroundColor', c_bg, 'BorderType', 'none');

    p_isolator = uipanel('Parent', fig, 'Units', 'normalized', ...
        'Position', [0 0 1 1], 'BackgroundColor', c_bg, 'BorderType', 'none', ...
        'Visible', 'off');

    p_circulator = uipanel('Parent', fig, 'Units', 'normalized', ...
        'Position', [0 0 1 1], 'BackgroundColor', c_bg, 'BorderType', 'none', ...
        'Visible', 'off');

    p_wdm = uipanel('Parent', fig, 'Units', 'normalized', ...
        'Position', [0 0 1 1], 'BackgroundColor', c_bg, 'BorderType', 'none', ...
        'Visible', 'off');

    % Populate Dashboard
    build_dashboard();

    % Track initialized modules
    isolator_init = false;
    circulator_init = false;
    wdm_init = false;

    % Store navigation callback in fig.UserData
    fig.UserData.on_back = @show_dashboard;

    % ---------------------------------------------------------------------
    % DASHBOARD BUILDER
    % ---------------------------------------------------------------------
